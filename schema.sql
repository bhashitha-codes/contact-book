-- Run this script in Supabase Dashboard -> SQL Editor -> New query.
-- Safe to re-run: it creates the table only if it does not already exist.

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  email text,
  contact_group text not null default 'Other',
  created_at timestamptz not null default now()
);

create index if not exists contacts_name_idx
  on public.contacts (name);

create index if not exists contacts_group_idx
  on public.contacts (contact_group);

-- This app accesses the database only through its Node.js server using the
-- service-role key stored in .env. Never put that key in frontend JavaScript.
-- The service-role key bypasses RLS, so keep it secret and do not deploy this
-- configuration publicly without adding authentication and authorization.
